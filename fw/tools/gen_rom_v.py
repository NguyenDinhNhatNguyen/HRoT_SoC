#!/usr/bin/env python3
"""Turn the two ROM images into synthesizable Verilog (P-21, phase 2 of the SRAM work).

    gen_rom_v.py <boot.hex> <app.hex> <rom_images.v>

boot.hex : $readmemh word file of the Boot ROM (fw/build/firmware_imem.hex)
app.hex  : $readmemh word file of the App ROM (fw/build/app_firmware.hex)
Writes the modules ROM_Image_Boot and ROM_Image_App: a combinational 1024 x 32 lookup (case on the
word address, zero words left to the default). rtl/mem/ROM_Logic.v wraps them with the ports of
Dual_Port_ROM. An SRAM macro cannot be a ROM (it has no content at power-up), so for the ASIC the
firmware is synthesized as logic. The file is generated for each firmware build and never committed
(build/ is ignored). Same hex format as golden.py ('@' markers and // comments are allowed).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from golden import read_hex  # noqa: E402  (also checks that a word lies inside the 4 KB)


def module(name, hex_path):
    words = read_hex(hex_path)
    lines = [
        "// %s: %d of 1024 words are not zero, from %s" % (
            name, sum(1 for w in words if w), os.path.basename(hex_path)),
        "module %s (" % name,
        "    input  wire [9:0]  a,",
        "    output reg  [31:0] d",
        ");",
        "    always @(*) begin",
        "        case (a)",
    ]
    for i, w in enumerate(words):
        if w:
            lines.append("            10'd%d: d = 32'h%08x;" % (i, w))
    lines += [
        "            default: d = 32'h00000000;",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    boot, app, out = sys.argv[1:]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by fw/tools/gen_rom_v.py, do not edit and do not commit.\n")
        f.write("`timescale 1ns / 1ps\n`default_nettype none\n\n")
        f.write(module("ROM_Image_Boot", boot) + "\n")
        f.write(module("ROM_Image_App", app) + "\n")
        f.write("`default_nettype wire\n")
    print("wrote %s" % out)


if __name__ == "__main__":
    main()
